/**
 * Generates the CSS custom properties in `global.css` from `theme-colors.json`.
 *
 * The palette has to exist twice — once for Tailwind (which resolves
 * `var(--c-*)` at build time into class definitions) and once for the handful
 * of React Native APIs that take a raw colour string. This script is what
 * stops the two drifting: `theme-colors.json` is the source, `global.css` is
 * generated, and `__tests__/theme.test.ts` fails if the file on disk no longer
 * matches the palette.
 *
 *   node scripts/build-theme-css.js         # write
 *   node scripts/build-theme-css.js --check # exit 1 if stale
 */
const fs = require('fs');
const path = require('path');

const palette = require('../theme-colors.json');

const kebab = (key) => key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const block = (scheme) =>
  Object.entries(palette[scheme])
    .map(([key, value]) => `    --c-${kebab(key)}: ${value};`)
    .join('\n');

const css = `@tailwind base;
@tailwind components;
@tailwind utilities;

/* Generated by scripts/build-theme-css.js from theme-colors.json — do not edit
   by hand. Colours are semantic: the same class means "page ground" or
   "secondary label" in both schemes, and only the value underneath changes.

   \`.dark:root\` is how NativeWind expresses the dark half of a class-based
   colour scheme; it applies on native as well as on the web. */
@layer base {
  :root {
${block('light')}
  }

  .dark:root {
${block('dark')}
  }
}
`;

const target = path.join(__dirname, '..', 'global.css');

if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (current !== css) {
    console.error('global.css is out of date — run `npm run theme`.');
    process.exit(1);
  }
  console.log('global.css matches theme-colors.json.');
} else {
  fs.writeFileSync(target, css);
  console.log(`Wrote ${target}`);
}

module.exports = { css };
